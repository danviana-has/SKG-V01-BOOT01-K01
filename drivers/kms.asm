section .text


kms_dispatch:

    ret

vbe_write:
    push dx
    push ax
    mov dx, VBE_DISPI_IOPORT_INDEX
    pop ax
    out dx, ax
    mov dx, VBE_DISPI_IOPORT_DATA
    mov ax, bx
    out dx, ax
    pop dx
    ret

kms_init:
    pusha
    ; Apos pusha (32 bytes) + ret addr (4) + magic 1o arg (4) + multiboot_info 2o arg (4)
    ; esp+32 = ret addr, esp+36 = magic, esp+40 = multiboot_info
    mov ebx, [esp + 40]          ; ebx = ponteiro multiboot_info

    cmp ebx, 0
    je .hardware_force

    ; Verifica flag bit 12 (framebuffer info presente na struct multiboot_info)
    mov eax, [ebx]
    test eax, (1 << 12)
    jz .hardware_force

    ; Multiboot 1 spec: framebuffer_addr esta no offset 88 (uint64, low 32 bits)
    mov eax, [ebx + 88]
    cmp eax, 0
    je .hardware_force

    ; Salva endereco do LFB fornecido pelo GRUB
    mov [kms_lfb_ptr], eax

    ; framebuffer_pitch esta no offset 96 (uint32, bytes por linha)
    mov eax, [ebx + 96]
    cmp eax, 0
    je .use_default_pitch
    mov [kms_pitch], eax
    jmp .do_clear               ; GRUB configurou tudo, nao resetar VBE!

.use_default_pitch:
    mov dword [kms_pitch], 4096
    jmp .do_clear

.hardware_force:
    ; Fallback: GRUB nao forneceu LFB, inicializa VBE Bochs via I/O
    mov ax, VBE_DISPI_INDEX_ENABLE
    mov bx, VBE_DISPI_DISABLED
    call vbe_write

    mov ax, VBE_DISPI_INDEX_XRES
    mov bx, 1024
    call vbe_write

    mov ax, VBE_DISPI_INDEX_YRES
    mov bx, 768
    call vbe_write

    mov ax, VBE_DISPI_INDEX_BPP
    mov bx, 32
    call vbe_write

    mov ax, VBE_DISPI_INDEX_ENABLE
    mov bx, VBE_DISPI_ENABLED | VBE_DISPI_LFB_ENABLED
    call vbe_write

    ; LFB padrao do VBE Bochs no VirtualBox (PCI BAR do adaptador VGA)
    mov dword [kms_lfb_ptr], 0xE0000000
    mov dword [kms_pitch], 4096

.do_clear:
    call kms_clear_screen
    popa
    ret

kms_clear_screen:
    pusha
    call kms_draw_wallpaper
    call kms_draw_terminal_box
    mov dword [kms_cursor_x], 35
    mov dword [kms_cursor_y], 55
    popa
    ret

kms_draw_wallpaper:
    pusha
    mov esi, wallpaper_bmp
    cmp word [esi], 0x4D42        ; Magic header 'BM'
    jne .done

    mov ebp, [esi + 10]           ; Offset dos pixels no BMP
    add ebp, esi                  ; ebp = ponteiro para inicio dos pixels

    mov ebx, 0                    ; ebx = y na tela (0..767)

.row_loop:
    cmp ebx, 768
    jge .done

    ; Endereço no LFB: edi = kms_lfb_ptr + ebx * pitch
    mov edi, ebx
    imul edi, [kms_pitch]
    add edi, [kms_lfb_ptr]

    ; Endereço no BMP (bottom-up): esi = ebp + (767 - ebx) * pitch
    mov eax, 767
    sub eax, ebx
    imul eax, [kms_pitch]
    add eax, ebp
    mov esi, eax

    ; Copia linha inteira de 1024 pixels (4096 bytes) de alta velocidade
    mov ecx, 1024
    rep movsd

    inc ebx
    jmp .row_loop

.done:
    popa
    ret

kms_draw_terminal_box:
    pusha

    ; 1. Barra de Titulo do Terminal (Y: 20..44)
    mov ebx, 20
.hdr_row:
    cmp ebx, 45
    jge .hdr_done

    mov edi, ebx
    imul edi, [kms_pitch]
    add edi, [kms_lfb_ptr]
    add edi, 20 * 4             ; X = 20

    mov ecx, 984                ; Largura 984 pixels
    cmp ebx, 20
    je .hdr_accent

    mov eax, 0x001E293B         ; Cor Slate Dark Glass para o cabeçalho
.hdr_loop:
    mov [edi], eax
    add edi, 4
    dec ecx
    jnz .hdr_loop
    inc ebx
    jmp .hdr_row

.hdr_accent:
    mov eax, 0x003B82F6         ; Linha de acento Azul Eletrico
    rep stosd
    inc ebx
    jmp .hdr_row

.hdr_done:

    ; 2. Area de Conteudo do Terminal em Vidro Fume Semitransparente (Y: 45..748)
    mov ebx, 45
.glass_row:
    cmp ebx, 748
    jge .glass_done

    mov edi, ebx
    imul edi, [kms_pitch]
    add edi, [kms_lfb_ptr]
    add edi, 20 * 4             ; X = 20

    mov ecx, 984                ; Largura 984 pixels
.glass_col:
    mov eax, [edi]              ; Le o pixel do Wallpaper de fundo
    and eax, 0x00FCFCFC         ; MASCARA CRUCIAL: Zera os 2 bits inferiores de R, G, B para evitar vazamento entre canais!
    shr eax, 2                  ; 25% da intensidade do wallpaper
    add eax, 0x000F172A         ; Adiciona tom escuro de vidro fume azulado
    mov [edi], eax              ; Grava no Framebuffer!
    add edi, 4
    dec ecx
    jnz .glass_col


    inc ebx
    jmp .glass_row

.glass_done:
    popa
    ret

kms_put_pixel:
    pusha
    cmp eax, [kms_width]
    jge .done
    cmp ebx, [kms_height]
    jge .done

    mov edx, ebx
    imul edx, [kms_pitch]
    mov edi, eax
    shl edi, 2
    add edi, edx
    add edi, [kms_lfb_ptr]
    mov [edi], ecx

.done:
    popa
    ret

kms_print_char:
    pusha
    movzx eax, al

    cmp al, 10
    je .newline
    cmp al, 8
    je .backspace

    ; Ponteiro para dados da fonte: font_8x8 + (char - 32) * 8
    movzx esi, al
    cmp al, 92                  ; Se ASCII >= 92 (], ^, _, `, a-z), ajusta o shift
    jl .no_adj
    dec esi
.no_adj:
    sub esi, 32                 ; (char - 32) = indice na tabela
    js .done                    ; char < 32 = controle, ignora
    shl esi, 3                  ; * 8 bytes por glifo
    add esi, font_8x8           ; esi = &font_8x8[(char-32)*8]

    mov edx, 0                  ; edx = linha atual (0..7)
.row_loop:
    cmp edx, 8
    jge .char_done

    movzx edi, byte [esi + edx] ; edi = byte de fonte para a linha edx
    mov ecx, 0                  ; ecx = coluna atual (0..7)

.col_loop:
    cmp ecx, 8
    jge .row_next

    mov eax, [kms_cursor_x]
    add eax, ecx                ; eax = x = cursor_x + coluna
    mov ebx, [kms_cursor_y]
    add ebx, edx                ; ebx = y = cursor_y + linha

    push ecx
    test edi, 0x80
    jz .pixel_done              ; Fundo transparente: nao sobrescreve o vidro!

    mov ecx, [kms_fg_color]
    call kms_put_pixel

.pixel_done:
    pop ecx                     ; restaura coluna
    shl edi, 1                  ; proximo bit do byte de fonte
    inc ecx                     ; proxima coluna
    jmp .col_loop

.row_next:
    inc edx
    jmp .row_loop

.char_done:
    add dword [kms_cursor_x], 8
    mov eax, [kms_width]
    sub eax, 30
    cmp [kms_cursor_x], eax
    jl .done
.newline:
    mov dword [kms_cursor_x], 35
    add dword [kms_cursor_y], 14
    mov eax, [kms_height]
    sub eax, 40
    cmp [kms_cursor_y], eax
    jl .done
    call kms_clear_screen
    jmp .done

.backspace:
    cmp dword [kms_cursor_x], 35
    jle .done
    sub dword [kms_cursor_x], 8

    ; Restaura o vidro translúcido limpo na célula de 8x14 pixels do caractere apagado
    mov ecx, 0                  ; ecx = linha y (0..13)
.bs_row:
    cmp ecx, 14
    jge .done
    mov edx, 0                  ; edx = coluna x (0..7)
.bs_col:
    cmp edx, 8
    jge .bs_next_row

    mov eax, [kms_cursor_x]
    add eax, edx                ; eax = x
    mov ebx, [kms_cursor_y]
    add ebx, ecx                ; ebx = y

    push ecx
    push edx

    ; 1. Endereço de destino no LFB: edi = kms_lfb_ptr + y * pitch + x * 4
    mov edi, ebx
    imul edi, [kms_pitch]
    mov edx, eax
    shl edx, 2
    add edi, edx
    add edi, [kms_lfb_ptr]

    ; 2. Endereço de origem no Wallpaper (bottom-up): esi = wallpaper_bmp + offset + (767 - y) * pitch + x * 4
    mov esi, wallpaper_bmp
    mov ebp, [esi + 10]         ; Offset dos pixels no BMP
    add ebp, esi

    mov esi, 767
    sub esi, ebx
    imul esi, [kms_pitch]
    add esi, ebp
    mov edx, eax
    shl edx, 2
    add esi, edx

    ; 3. Le o pixel original do wallpaper, aplica a mascara e o vidro fume
    mov eax, [esi]
    and eax, 0x00FCFCFC
    shr eax, 2
    add eax, 0x000F172A
    mov [edi], eax              ; Grava a celula limpa de vidro no Framebuffer!

    pop edx
    pop ecx
    inc edx
    jmp .bs_col

.bs_next_row:
    inc ecx
    jmp .bs_row


.done:
    popa
    ret


kms_print_string:
    pusha
.s_loop:
    mov al, [esi]
    cmp al, 0
    je .s_done
    call kms_print_char
    inc esi
    jmp .s_loop
.s_done:
    popa
    ret

