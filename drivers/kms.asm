section .text


kms_dispatch:

    ret

vbe_write:
    push dx
    push ax
    mov dx, VBE_DISPI_IOPORT_INDEX
    pop ax
    out dx, ax
    mov dx, VBE_DISPI_IOPORT_DATA
    mov ax, bx
    out dx, ax
    pop dx
    ret

kms_init:
    pusha
    ; Apos pusha (32 bytes) + ret addr (4) + magic 1o arg (4) + multiboot_info 2o arg (4)
    ; esp+32 = ret addr, esp+36 = magic, esp+40 = multiboot_info
    mov ebx, [esp + 40]          ; ebx = ponteiro multiboot_info

    cmp ebx, 0
    je .hardware_force

    ; Verifica flag bit 12 (framebuffer info presente na struct multiboot_info)
    mov eax, [ebx]
    test eax, (1 << 12)
    jz .hardware_force

    ; Multiboot 1 spec: framebuffer_addr esta no offset 88 (uint64, low 32 bits)
    mov eax, [ebx + 88]
    cmp eax, 0
    je .hardware_force

    ; Salva endereco do LFB fornecido pelo GRUB
    mov [kms_lfb_ptr], eax

    ; framebuffer_pitch esta no offset 96 (uint32, bytes por linha)
    mov eax, [ebx + 96]
    cmp eax, 0
    je .use_default_pitch
    mov [kms_pitch], eax
    jmp .do_clear               ; GRUB configurou tudo, nao resetar VBE!

.use_default_pitch:
    mov dword [kms_pitch], 4096
    jmp .do_clear

.hardware_force:
    ; Fallback: GRUB nao forneceu LFB, inicializa VBE Bochs via I/O
    mov ax, VBE_DISPI_INDEX_ENABLE
    mov bx, VBE_DISPI_DISABLED
    call vbe_write

    mov ax, VBE_DISPI_INDEX_XRES
    mov bx, 1024
    call vbe_write

    mov ax, VBE_DISPI_INDEX_YRES
    mov bx, 768
    call vbe_write

    mov ax, VBE_DISPI_INDEX_BPP
    mov bx, 32
    call vbe_write

    mov ax, VBE_DISPI_INDEX_ENABLE
    mov bx, VBE_DISPI_ENABLED | VBE_DISPI_LFB_ENABLED
    call vbe_write

    ; LFB padrao do VBE Bochs no VirtualBox (PCI BAR do adaptador VGA)
    mov dword [kms_lfb_ptr], 0xE0000000
    mov dword [kms_pitch], 4096

.do_clear:
    call kms_clear_screen
    popa
    ret

kms_clear_screen:
    pusha
    mov edi, [kms_lfb_ptr]
    mov eax, 1024 * 768
    mov ecx, eax
    mov eax, [kms_bg_color]
    rep stosd
    mov dword [kms_cursor_x], 20
    mov dword [kms_cursor_y], 20
    popa
    ret

kms_put_pixel:
    pusha
    cmp eax, [kms_width]
    jge .done
    cmp ebx, [kms_height]
    jge .done

    mov edx, ebx
    imul edx, [kms_pitch]
    mov edi, eax
    shl edi, 2
    add edi, edx
    add edi, [kms_lfb_ptr]
    mov [edi], ecx

.done:
    popa
    ret

kms_print_char:
    pusha
    movzx eax, al

    cmp al, 10
    je .newline
    cmp al, 8
    je .backspace

    ; Ponteiro para dados da fonte: font_8x8 + (char - 32) * 8
    movzx esi, al
    cmp al, 92                  ; Se ASCII >= 92 (], ^, _, `, a-z), ajusta o shift
    jl .no_adj
    dec esi
.no_adj:
    sub esi, 32                 ; (char - 32) = indice na tabela
    js .done                    ; char < 32 = controle, ignora
    shl esi, 3                  ; * 8 bytes por glifo
    add esi, font_8x8           ; esi = &font_8x8[(char-32)*8]



    mov edx, 0                  ; edx = linha atual (0..7)
.row_loop:
    cmp edx, 8
    jge .char_done

    ; Usar EDI para guardar o byte da fonte (nao CL/CH!)
    ; assim nao conflita com ecx que kms_put_pixel sobrescreve via popa
    movzx edi, byte [esi + edx] ; edi = byte de fonte para a linha edx
    mov ecx, 0                  ; ecx = coluna atual (0..7)

.col_loop:
    cmp ecx, 8
    jge .row_next

    mov eax, [kms_cursor_x]
    add eax, ecx                ; eax = x = cursor_x + coluna
    mov ebx, [kms_cursor_y]
    add ebx, edx                ; ebx = y = cursor_y + linha

    ; Salva ecx (coluna) antes de sobrescrever com cor
    push ecx
    test edi, 0x80
    jz .bg_pixel

    mov ecx, [kms_fg_color]
    call kms_put_pixel
    jmp .pixel_done

.bg_pixel:
    mov ecx, [kms_bg_color]
    call kms_put_pixel

.pixel_done:
    pop ecx                     ; restaura coluna
    shl edi, 1                  ; proximo bit do byte de fonte
    inc ecx                     ; proxima coluna
    jmp .col_loop

.row_next:
    inc edx
    jmp .row_loop

.char_done:
    add dword [kms_cursor_x], 8
    mov eax, [kms_width]
    sub eax, 10
    cmp [kms_cursor_x], eax
    jl .done
.newline:
    mov dword [kms_cursor_x], 20
    add dword [kms_cursor_y], 12
    mov eax, [kms_height]
    sub eax, 16
    cmp [kms_cursor_y], eax
    jl .done
    call kms_clear_screen
    jmp .done

.backspace:
    cmp dword [kms_cursor_x], 20
    jle .done
    sub dword [kms_cursor_x], 8
    mov ecx, 0
.bs_row:
    cmp ecx, 8
    jge .done
    mov edx, 0
.bs_col:
    cmp edx, 8
    jge .bs_next_row
    mov eax, [kms_cursor_x]
    add eax, edx
    mov ebx, [kms_cursor_y]
    add ebx, ecx
    push ecx
    mov ecx, [kms_bg_color]
    call kms_put_pixel
    pop ecx
    inc edx
    jmp .bs_col
.bs_next_row:
    inc ecx
    jmp .bs_row

.done:
    popa
    ret


kms_print_string:
    pusha
.s_loop:
    mov al, [esi]
    cmp al, 0
    je .s_done
    call kms_print_char
    inc esi
    jmp .s_loop
.s_done:
    popa
    ret